"""Evidence-sentence correctness audit (Issue #11: "audit evidence
sentence correctness").

Positive cases run the audit over attributions ACTUALLY generated by
the evidence module; negative cases prove the audit detects fabricated
offsets and broken claim ids rather than rubber-stamping.
"""

from __future__ import annotations

from paperdna.api.pipeline import DEMO_CORPUS_PATH
from paperdna.claims.extractor import extract_claims
from paperdna.corpus.ingest import ingest_records, load_jsonl
from paperdna.evidence.build import (
    attribute_from_classification,
    build_attribution,
)
from paperdna.evidence.schema import (
    ClaimRef,
    PaperRef,
    SentenceEvidence,
    claim_id_for,
)
from paperdna.eval.evidence_audit import audit_attributions, audit_side


def _demo_records():
    return ingest_records(load_jsonl(str(DEMO_CORPUS_PATH))).papers


def _first_record_with_claim(records):
    """The first demo record from which the extractor yields a claim."""
    for record in records:
        claims = extract_claims(record).claims
        if claims:
            return record, claims[0]
    raise AssertionError("demo corpus yielded no claims at all")


def _abstracts(records):
    return {(r.source, r.source_id): r.abstract for r in records}


class TestAuditOnGeneratedAttributions:
    def test_zero_violations_over_demo_corpus_claims(self):
        records = _demo_records()
        attributions = [
            build_attribution(claim, claim, records=records)
            for record in records
            for claim in extract_claims(record).claims
        ]
        assert attributions, "demo corpus must yield claims to audit"
        report = audit_attributions(attributions, records)
        assert report["n_violations"] == 0, report["violations"]
        assert report["n_evidence_sides"] == 2 * report["n_attributions"]
        assert (
            sum(report["verification_counts"].values()) == report["n_evidence_sides"]
        )

    def test_unrecorded_claims_are_honestly_unverified(self):
        records = _demo_records()
        _, claim = _first_record_with_claim(records)
        attribution = build_attribution(claim, claim, records=())
        report = audit_attributions([attribution], records)
        assert report["n_violations"] == 0
        assert report["verification_counts"] == {"unverified": 2}
        assert attribution.premise.unavailable_reason

    def test_classification_only_path_offsets_are_inferred_not_guessed(self):
        from paperdna.nli.schema import RELATIONSHIPS, PairClassification

        records = _demo_records()
        _, claim = _first_record_with_claim(records)
        other = records[1]  # a real record whose abstract lacks the sentence below
        classification = PairClassification(
            premise_source=claim.source,
            premise_source_id=claim.source_id,
            premise_text=claim.sentence,
            hypothesis_source=other.source,
            hypothesis_source_id=other.source_id,
            hypothesis_text="A sentence that appears nowhere in any abstract.",
            label=max(RELATIONSHIPS),
            scores={label: 0.34 for label in RELATIONSHIPS},
            confidence=0.34,
            uncertain=True,
            hedged=False,
            truncated=False,
            model="audit-fixture",
        )
        attribution = attribute_from_classification(classification, records=records)
        # Premise: sentence occurs in the abstract -> inferred offsets.
        assert attribution.premise.verification == "verified_by_search"
        assert attribution.premise.claim.start is not None
        # Hypothesis: absent from every abstract -> unavailable, no offsets.
        assert attribution.hypothesis.verification == "unavailable"
        assert attribution.hypothesis.claim.start is None
        assert attribution.hypothesis.claim.claim_id.endswith(":unknown")

        report = audit_attributions([attribution], records)
        assert report["n_violations"] == 0, report["violations"]


class TestAuditDetectsBrokenEvidence:
    def _verified_side(self, record, claim) -> SentenceEvidence:
        return SentenceEvidence(
            paper=PaperRef(source=record.source, source_id=record.source_id,
                           title=record.title),
            claim=ClaimRef(
                claim_id=claim_id_for(record.source, record.source_id,
                                      claim.start, claim.end),
                source=record.source, source_id=record.source_id,
                start=claim.start, end=claim.end,
            ),
            sentence=claim.sentence,
            verification="verified",
        )

    def test_fabricated_offsets_are_caught(self):
        record, claim = _first_record_with_claim(_demo_records())
        side = self._verified_side(record, claim)
        broken = SentenceEvidence(
            paper=side.paper,
            claim=ClaimRef(
                claim_id=claim_id_for(record.source, record.source_id,
                                      claim.start + 1, claim.end),
                source=record.source, source_id=record.source_id,
                start=claim.start + 1, end=claim.end,
            ),
            sentence=claim.sentence,
            verification="verified",
        )
        problems = audit_side(broken, _abstracts([record]))
        assert problems and "does not equal the evidence sentence" in problems[0]

    def test_broken_claim_id_is_caught(self):
        record, claim = _first_record_with_claim(_demo_records())
        side = self._verified_side(record, claim)
        broken = SentenceEvidence(
            paper=side.paper,
            claim=ClaimRef(
                claim_id="arxiv:forged:0-1",
                source=record.source, source_id=record.source_id,
                start=claim.start, end=claim.end,
            ),
            sentence=claim.sentence,
            verification="verified",
        )
        problems = audit_side(broken, _abstracts([record]))
        assert problems and "claim_id" in problems[0]

    def test_clean_side_passes(self):
        record, claim = _first_record_with_claim(_demo_records())
        assert audit_side(self._verified_side(record, claim), _abstracts([record])) == []
